import subprocess, time, os

# ---- 1. Read all secrets you stored in Colab ----
from google.colab import userdata

NGROK_TOKEN = userdata.get("NGROK_AUTHTOKEN")
print("NGROK_AUTHTOKEN loaded:", "✅" if NGROK_TOKEN else "❌ empty")

# ALSO export as env var (pyngrok reads this as fallback)
os.environ["NGROK_AUTHTOKEN"] = NGROK_TOKEN

# ---- 2. Start uvicorn ----
subprocess.run(["pkill", "-f", "uvicorn"], capture_output=True)
log = open("uvicorn.log", "w")
proc = subprocess.Popen(
    ["uvicorn", "main:app", "--host", "0.0.0.0", "--port", "8000"],
    stdout=log, stderr=log,
)
time.sleep(5)
print("=== uvicorn log ===")
print(open("uvicorn.log").read()[-800:])

# ---- 3. Configure ngrok (token FIRST, kill AFTER) ----
from pyngrok import ngrok, conf

conf.get_default().auth_token = NGROK_TOKEN
ngrok.set_auth_token(NGROK_TOKEN)
ngrok.kill()          # kill AFTER setting token
time.sleep(1)

# ---- 4. Connect ----
try:
    public_url = ngrok.connect(8000, "http").public_url
    print("\n🌍 PUBLIC URL:", public_url)
    print("📖 Swagger  :", public_url + "/docs")
    print("🔎 ReDoc    :", public_url + "/redoc")
except Exception as e:
    print("❌ ngrok failed:", e)
    print("Log tail:")
    print(open("uvicorn.log").read()[-1000:])